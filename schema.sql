create table if not exists public.book_ratings (
  id bigint generated by default as identity primary key,
  book_id text not null,
  voter_id text not null,
  rating int not null check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  unique (book_id, voter_id)
);
alter table public.book_ratings enable row level security;
create policy "Anyone can read ratings" on public.book_ratings for select using (true);
create policy "Anyone can submit a rating" on public.book_ratings for insert with check (rating between 1 and 5 and length(voter_id) between 20 and 80);
create policy "Voters can update their own rating" on public.book_ratings for update using (length(voter_id) between 20 and 80) with check (rating between 1 and 5 and length(voter_id) between 20 and 80);
grant select, insert, update on public.book_ratings to anon;
grant usage, select on sequence public.book_ratings_id_seq to anon;
